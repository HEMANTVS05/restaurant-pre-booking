// Helper: search by region (case-insensitive partial match)
function searchRestaurantsByRegion(query) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return RESTAURANTS_DB.filter(r => r.region.includes(q));
}

// Helper: get unique regions
function getAllRegions() {
  return [...new Set(RESTAURANTS_DB.map(r => r.region))].sort();
}

